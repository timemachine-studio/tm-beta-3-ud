async function publishToRegistry(spec: ToolSpec, digest: string): Promise<PublishResult> {
  // Imported here so a turn that only saved a note does not pull the
  // Supabase client into the device-tool path.
  const { publishTool } = await import('../tools/toolRegistryService');
  return publishTool(spec, digest);
}

async function rememberPublication(spec: ToolSpec, digest: string, result: PublishResult): Promise<boolean> {
  const { publicationIsRetryable, queueToolPublication, recordPublishedTool } = await import('../tools/toolPublicationQueue');
  if (result.published) {
    await recordPublishedTool(digest, { id: result.id, version: result.version });
    return false;
  }
  return publicationIsRetryable(result) && await queueToolPublication(spec, digest);
}

async function registryToolActive(id: string, digest: string): Promise<boolean> {
  const { isRegistryToolActive } = await import('../tools/toolRegistryService');
  return isRegistryToolActive(id, digest);
}

async function runInSharedRuntime(code: string, options?: PythonRunOptions): Promise<PythonRunOutcome> {
  // Imported here, not at the top: this module is on the path of every device
  // tool, and Pyodide must not be fetched by a turn that saved a note.
  const { pythonRuntime } = await import('../python/pythonRuntime');
  return pythonRuntime().run(code, options);
}

/**
 * Bytes from a run, into the device file store.
 *
 * Returns null rather than throwing, because a chart that could not be saved
 * must not lose the answer that came with it. The artifact is still produced,
 * marked as having no payload, and the reason is logged — the user is told
 * something is missing rather than shown a card with a hole in it.
 */
const storeArtifactFile: SaveArtifactFile = async (name, mime, bytes) => {
  try {
    const { putFile } = await import('../files/fileStore');
    const stored = await putFile({ name, mime, bytes, source: 'python' });
    return stored.id;
  } catch (error: unknown) {
    console.error('Could not store a generated file:', error instanceof Error ? error.message : error);
    return null;
  }
};

/**
 * Which device apps hold something worth searching, right now.
 *
 * The server uses this to leave readers out of a request that has nothing for
 * them to read — worth roughly a thousand tokens on every message from someone
 * who has not written a note or had a conversation yet, which is most people on
 * the free tier. Writers are never gated this way: notes_create is how an empty
 * store stops being empty.
 */
export async function resolveDeviceDataPresent(currentChatSessionId?: string): Promise<DeviceApp[]> {
  const present: DeviceApp[] = [];

  try {
    if (readNotes().length > 0) present.push('notes');
  } catch {
    // Unreadable storage is not proof of an empty one. Offer the tools and let
    // the lookup report the real failure.
    present.push('notes');
  }

  if (await chatService.hasArchive(currentChatSessionId)) present.push('chats');
  try {
    if (await privateSkillRepository.hasSkills()) present.push('private-skills');
  } catch {
    // A storage failure is not evidence of an empty library. Offer the reader
    // so the real error reaches the run instead of silently hiding skills.
    present.push('private-skills');
  }

  return present;
}

