/**
 * Executes the tools the server cannot: the ones whose data lives here.
 *
 * The server offers these to the model, then suspends the run and streams the
 * calls down. This runs them against local storage and hands back strings for
 * the transcript, plus — for anything that created or changed a real object —
 * a reference the chat renders as a card.
 */

export interface DeviceToolOutcome {
  content: string;
  appObject?: AppObjectRef;
  /** What a run_python call produced, for the chat to render under the answer. */
  pythonRun?: PythonRun;
  /** A tool this call wrote and tested. The conversation keeps it from here. */
  createdTool?: SessionTool;
}

/** What a workspace tool hands back, before it becomes a card. */
export interface WorkspaceToolResult {
  /** For the transcript. */
  content: string;
  ok: boolean;
  /** For the card — see HarnessAction. */
  path?: string;
  detail?: string;
  output?: string;
}

/**
 * Runs Max Mode's workspace tools (shared/maxMode.ts). Supplied by the
 * harness rather than imported here, so a turn that saved a note never loads
 * the workspace store, the Node runtime or the preview.
 */
export interface WorkspaceToolExecutor {
  run: (
    name: WorkspaceToolName,
    args: Record<string, unknown>,
    context: { onStatus?: (status: string) => void },
  ) => Promise<WorkspaceToolResult>;
}

export interface DeviceToolContext {
  signal?: AbortSignal;
  /** Stable for every retry of one user turn; used for idempotent writes. */
  runId?: string;
  /** The chat this turn belongs to, excluded from history search as redundant. */
  currentChatSessionId?: string;
  /** Shimmer text, so the user can see which app is being touched. */
  onStatus?: (status: string) => void;
  /**
   * Where Python runs. Defaults to the shared Pyodide worker, loaded on first
   * use — a parameter so that nothing imports ten megabytes of WebAssembly
   * into a process that only wants to check a note was saved.
   */
  runPython?: (code: string, options?: PythonRunOptions) => Promise<PythonRunOutcome>;
  /** Where generated bytes go. Defaults to the device file store. */
  saveFile?: SaveArtifactFile;
  /**
   * Files the user attached, to be mounted under /files before the code runs.
   * Names are already unique — the same strings the model was told about.
   */
  attachedFiles?: readonly AttachedFile[];
  /**
   * Tools this conversation already created. A call to one of them is
   * answered from here — its code never travels — and create_tool checks the
   * count against MAX_SESSION_TOOLS.
   */
  sessionTools?: readonly SessionTool[];
  /**
   * Where a new tool is published. Defaults to the shared registry through
   * the user's own Supabase session; a parameter so a test can watch it
   * happen without a network.
   */
  publishTool?: (spec: ToolSpec, digest: string) => Promise<PublishResult>;
  /** Recheck central revocation immediately before running published code. */
  registryToolActive?: (id: string, digest: string) => Promise<boolean>;
  /** Max Mode's workspace tools. Absent outside the harness, so a call is refused. */
  workspace?: WorkspaceToolExecutor;
  /** A harness card appearing or settling. */
  onHarnessAction?: (action: HarnessAction) => void;
}

/**
 * Load attachments out of the device store, ready to write into the sandbox.
 *
 * A file that cannot be read is skipped rather than fatal: it will surface as
 * the FileNotFoundError the model's own code raises, which names the path it
 * asked for. Failing the whole run would say less and cost the turn.
 */
async function resolveMounts(files: readonly AttachedFile[]): Promise<PythonMount[]> {
  if (files.length === 0) return [];
  const { readFile } = await import('../files/fileStore');
  const mounts: PythonMount[] = [];
  for (const file of files) {
    try {
      const blob = await readFile(file.id);
      if (blob) mounts.push({ id: file.id, name: file.name, bytes: new Uint8Array(await blob.arrayBuffer()) });
    } catch (error: unknown) {
      console.error('Could not read an attachment:', error instanceof Error ? error.message : error);
    }
  }
  return mounts;
}

